    public PlayerDatabase GetUser(string usedEmail, string usedPassword)
    {
		return _connection.Table<PlayerDatabase>().Where(x => x.Email == usedEmail && x.Password == usedPassword).FirstOrDefault();
	}

    public PlayerDatabase CreatePlayerInPlayerDatabase()
    {
		var pd = new PlayerDatabase{
				Email = "Markk",
				PlayTime = 0,
		};
		_connection.Insert (pd);
		return pd;
	}

